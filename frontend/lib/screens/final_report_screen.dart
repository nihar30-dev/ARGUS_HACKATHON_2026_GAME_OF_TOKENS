// ── Parsed data classes ───────────────────────────────────────────────────────

class _Phase {
  final String phase;
  final String duration;
  final String approach;

  _Phase({required this.phase, required this.duration, required this.approach});

  factory _Phase.fromMap(Map<String, dynamic> m) => _Phase(
        phase: m['phase'] as String? ?? '',
        duration: m['duration'] as String? ?? '',
        approach: m['approach'] as String? ?? '',
      );
}

class _Objection {
  final String objection;
  final String response;
  final String severity;
  final bool criticRevised;

  _Objection({
    required this.objection,
    required this.response,
    required this.severity,
    required this.criticRevised,
  });

  factory _Objection.fromMap(Map<String, dynamic> m) => _Objection(
        objection: m['objection'] as String? ?? '',
        response: m['response'] as String? ?? '',
        severity: m['severity'] as String? ?? 'MEDIUM',
        criticRevised: m['criticRevised'] as bool? ?? false,
      );
}

// ── Screen ────────────────────────────────────────────────────────────────────

class FinalReportScreen extends StatefulWidget {
  final SessionResponse session;

  const FinalReportScreen({super.key, required this.session});

  @override
  State<FinalReportScreen> createState() => _FinalReportScreenState();
}

class _FinalReportScreenState extends State<FinalReportScreen> {
  final Set<int> _expandedObjections = {0, 1, 2};

  // Parsed from JSON once
  late final List<_Phase> _phases;
  late final List<String> _questions;
  late final List<_Objection> _objections;
  late final List<String> _dos;
  late final List<String> _donts;
  late final List<String> _nextSteps;

  @override
  void initState() {
    super.initState();
    final report = widget.session.finalReport;
    _phases = _parseList(
        report?.conversationFlowJson, (m) => _Phase.fromMap(m));
    _questions = _parseStringList(report?.questionsJson);
    _objections = _parseList(
        report?.objectionResponsesJson, (m) => _Objection.fromMap(m));
    _nextSteps = _parseStringList(report?.nextStepsJson);

    final doAndDont = _parseMap(report?.doAndDontJson);
    _dos = _toStringList(doAndDont['dos']);
    _donts = _toStringList(doAndDont['donts']);
  }

  static List<T> _parseList<T>(
      String? json, T Function(Map<String, dynamic>) fn) {
    if (json == null) return [];
    try {
      return (jsonDecode(json) as List<dynamic>)
          .map((e) => fn(e as Map<String, dynamic>))
          .toList();
    } catch (_) {
      return [];
    }
  }

  static List<String> _parseStringList(String? json) {
    if (json == null) return [];
    try {
      return (jsonDecode(json) as List<dynamic>)
          .map((e) => e.toString())
          .toList();
    } catch (_) {
      return [];
    }
  }

  static Map<String, dynamic> _parseMap(String? json) {
    if (json == null) return {};
    try {
      return jsonDecode(json) as Map<String, dynamic>;
    } catch (_) {
      return {};
    }
  }

  static List<String> _toStringList(dynamic v) {
    if (v is List) return v.map((e) => e.toString()).toList();
    return [];
  }

  void _copyReport() {
    final report = widget.session.finalReport;
    final buf = StringBuffer();
    buf.writeln('MEETING BRIEF — ${widget.session.organizationName}');
    buf.writeln(
        'Generated by MeetWise · ${widget.session.agentRuns.length} Agents · '
        'Readiness: ${((report?.overallConfidence ?? 0) * 100).toStringAsFixed(0)}%');
    buf.writeln();

    if (report?.executiveBrief != null) {
      buf.writeln('EXECUTIVE BRIEF');
      buf.writeln(report!.executiveBrief);
      buf.writeln();
    }

    if (_phases.isNotEmpty) {
      buf.writeln('CONVERSATION FLOW');
      for (var i = 0; i < _phases.length; i++) {
        final p = _phases[i];
        buf.writeln('${i + 1}. ${p.phase} (${p.duration})');
        buf.writeln('   ${p.approach}');
      }
      buf.writeln();
    }

    if (_questions.isNotEmpty) {
      buf.writeln('QUESTIONS TO ASK');
      for (var i = 0; i < _questions.length; i++) {
        buf.writeln('${i + 1}. ${_questions[i]}');
      }
      buf.writeln();
    }

    if (_objections.isNotEmpty) {
      buf.writeln('OBJECTIONS & RESPONSES');
      for (final o in _objections) {
        buf.writeln('Q: ${o.objection}');
        buf.writeln('A: ${o.response}');
        buf.writeln();
      }
    }

    if (_dos.isNotEmpty) {
      buf.writeln('DO');
      for (final d in _dos) {
        buf.writeln('✓ $d');
      }
      buf.writeln();
    }

    if (_donts.isNotEmpty) {
      buf.writeln("DON'T");
      for (final d in _donts) {
        buf.writeln('✗ $d');
      }
      buf.writeln();
    }

    if (_nextSteps.isNotEmpty) {
      buf.writeln('NEXT STEPS');
      for (var i = 0; i < _nextSteps.length; i++) {
        buf.writeln('${i + 1}. ${_nextSteps[i]}');
      }
    }

    Clipboard.setData(ClipboardData(text: buf.toString()));

    ScaffoldMessenger.of(context).showSnackBar(
      const SnackBar(
        content: Row(
          children: [
            Icon(Icons.check_circle_outline, color: Colors.white, size: 16),
            SizedBox(width: AppSpacing.sm),
            Text('Report copied to clipboard'),
          ],
        ),
        duration: Duration(seconds: 2),
      ),
    );
  }

  @override
  Widget build(BuildContext context) {
    final report = widget.session.finalReport;
    if (report == null) {
      return Scaffold(
        appBar: AppBar(
          title: Text('Meeting Brief — ${widget.session.organizationName}'),
        ),
        body: ErrorView(
          compact: false,
          isError: false,
          icon: Icons.article_outlined,
          title: 'Report Not Ready',
          message:
              'The final meeting brief has not been generated yet. '
              'The agent pipeline may still be running.\n\n'
              'Check the Agent Trace view for pipeline status.',
          onRetry: () => Navigator.pushReplacementNamed(
              context, Routes.trace,
              arguments: widget.session),
          retryLabel: 'View Agent Trace',
          onSecondary: () => Navigator.pop(context),
          secondaryLabel: 'Go Back',
        ),
      );
    }

    return Scaffold(
      appBar: _buildAppBar(context),
      body: SingleChildScrollView(
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.stretch,
          children: [
            _ReadinessHero(session: widget.session, onCopy: _copyReport),
            Padding(
              padding: Responsive.pagePadding(context),
              child: Responsive.centered(
                context,
                Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    if (report.executiveBrief != null) ...[
                      _ExecutiveBriefCard(brief: report.executiveBrief!),
                      AppSpacing.gapLg,
                    ],
                    if (_phases.isNotEmpty) ...[
                      _ConversationFlowCard(phases: _phases),
                      AppSpacing.gapLg,
                    ],
                    if (_questions.isNotEmpty) ...[
                      _QuestionsCard(questions: _questions),
                      AppSpacing.gapLg,
                    ],
                    if (_objections.isNotEmpty) ...[
                      _ObjectionsCard(
                        objections: _objections,
                        expanded: _expandedObjections,
                        onToggle: (i) => setState(() =>
                            _expandedObjections.contains(i)
                                ? _expandedObjections.remove(i)
                                : _expandedObjections.add(i)),
                      ),
                      AppSpacing.gapLg,
                    ],
                    if (_dos.isNotEmpty || _donts.isNotEmpty) ...[
                      _DoAndDontCard(dos: _dos, donts: _donts),
                      AppSpacing.gapLg,
                    ],
                    if (_nextSteps.isNotEmpty) ...[
                      _NextStepsCard(steps: _nextSteps),
                      AppSpacing.gapLg,
                    ],
                    _AgentFooter(session: widget.session),
                    AppSpacing.gapXl,
                  ],
                ),
              ),
            ),
          ],
        ),
      ),
    );
  }

  PreferredSizeWidget _buildAppBar(BuildContext context) => AppBar(
        title: Text('Meeting Brief — ${widget.session.organizationName}'),
        actions: [
          TextButton.icon(
            onPressed: () => Navigator.pushNamed(
                context, Routes.trace,
                arguments: widget.session),
            icon: const Icon(Icons.account_tree_outlined, size: 16),
            label: const Text('Agent Trace'),
          ),
          IconButton(
            onPressed: _copyReport,
            tooltip: 'Copy report',
            icon: const Icon(Icons.copy_outlined, size: 18),
          ),
          const SizedBox(width: AppSpacing.sm),
        ],
      );
}


        horizontal: isMobile ? AppSpacing.lg : AppSpacing.xxxl,
        vertical: isMobile ? AppSpacing.xxl : AppSpacing.xxxl,
      ),
      child: Responsive.centered(
        context,
        isMobile
            ? Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [

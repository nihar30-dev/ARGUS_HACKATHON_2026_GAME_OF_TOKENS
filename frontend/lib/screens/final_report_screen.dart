// ── Conversation flow ─────────────────────────────────────────────────────────

class _ConversationFlowCard extends StatelessWidget {
  final List<_Phase> phases;

  const _ConversationFlowCard({required this.phases});

  // Total minutes for the overall duration indicator
  int get _totalMinutes {
    int total = 0;
    for (final p in phases) {
      final match = RegExp(r'(\d+)').firstMatch(p.duration);
      if (match != null) total += int.tryParse(match.group(1)!) ?? 0;
    }
    return total;
  }

  @override
  Widget build(BuildContext context) {
    return SectionCard(
      icon: Icons.timeline_outlined,
      iconColor: AppColors.accent,
      iconBg: AppColors.accentSubtle,
      title: 'Conversation Flow',
      subtitle: '${phases.length} phases  ·  ~$_totalMinutes minutes',
      child: Column(
        children: [
          for (var i = 0; i < phases.length; i++)
            _PhaseRow(
                phase: phases[i], index: i, isLast: i == phases.length - 1),
        ],
      ),
    );
  }
}

